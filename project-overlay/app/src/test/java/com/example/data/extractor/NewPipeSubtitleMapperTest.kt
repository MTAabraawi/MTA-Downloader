package com.example.data.extractor

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test

class NewPipeSubtitleMapperTest {
    @Test
    fun mapsManualAndAutomaticSubtitleMetadata() {
        val manual = NewPipeSubtitleMapper.toQualityOption(
            url = "https://cdn.example.test/subtitles/ar.vtt",
            languageTag = "ar",
            displayLanguageName = "العربية",
            isAutoGenerated = false,
            formatSuffix = "vtt",
            formatName = "WebVTT",
            mimeType = "text/vtt"
        )
        val automatic = NewPipeSubtitleMapper.toQualityOption(
            url = "https://cdn.example.test/subtitles/en.vtt",
            languageTag = "en",
            displayLanguageName = "",
            isAutoGenerated = true,
            formatSuffix = "vtt",
            formatName = "WebVTT",
            mimeType = "text/vtt"
        )
        assertEquals("ترجمة • العربية", manual?.label)
        assertEquals("ترجمة • en • تلقائية", automatic?.label)
        assertEquals("text/vtt", manual?.mimeType)
        assertEquals("https://cdn.example.test/subtitles/ar.vtt", manual?.overrideStreamUrl)
    }

    @Test
    fun rejectsNonHttpsOrIncompleteSubtitleStreams() {
        assertNull(
            NewPipeSubtitleMapper.toQualityOption(
                url = "http://cdn.example.test/subtitles/ar.vtt",
                languageTag = "ar",
                displayLanguageName = "العربية",
                isAutoGenerated = false,
                formatSuffix = "vtt",
                formatName = "WebVTT",
                mimeType = "text/vtt"
            )
        )
        assertNull(
            NewPipeSubtitleMapper.toQualityOption(
                url = "https://cdn.example.test/subtitles/ar.vtt",
                languageTag = "",
                displayLanguageName = "العربية",
                isAutoGenerated = false,
                formatSuffix = "vtt",
                formatName = "WebVTT",
                mimeType = "text/vtt"
            )
        )
    }
}
