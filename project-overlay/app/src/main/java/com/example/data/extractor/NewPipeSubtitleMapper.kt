package com.example.data.extractor

import com.example.data.model.QualityOption

internal object NewPipeSubtitleMapper {
    fun toQualityOption(
        url: String,
        languageTag: String,
        displayLanguageName: String,
        isAutoGenerated: Boolean,
        formatSuffix: String,
        formatName: String,
        mimeType: String
    ): QualityOption? {
        if (!url.startsWith("https://", ignoreCase = true)) return null
        if (languageTag.isBlank() || formatSuffix.isBlank() || mimeType.isBlank()) return null
        val language = displayLanguageName.ifBlank { languageTag }
        val generated = if (isAutoGenerated) " • تلقائية" else ""
        return QualityOption(
            id = "newpipe_subtitle_\${languageTag}_\${formatSuffix}",
            label = "ترجمة • \${language}\${generated}",
            format = formatName,
            sizeEstimate = "حجم غير متاح",
            extension = formatSuffix,
            mimeType = mimeType,
            overrideStreamUrl = url
        )
    }
}
